import os
from collections import defaultdict

import cerebras.sdk.debug.lib.symbol.csldebugpybind as CSLDebug
from cerebras.elf.cself import ELFMemory
from cerebras.elf.csl import get_color_info, has_color_info
from cerebras.hwdebug_common.viz_service.base import ERROR_CODES, HTTPJsonError


class CompileCache:
    """
    This class survives multiple REST api calls by being kept in
    the plugin manager directory under indexed by path name

    This class should keep information that is repetitive, like
    examining the directories for artifacts, creating HAL/DAS contexts
    for debugging apis

    """

    COLOR_INFO = "color_info"

    def __init__(self, artifactdirectory):
        """ provide a cache of data for a specific directory

        Generally, when a user requests information from a directory,
        we need to find out what artifacts are available and what
        data that we can parse.
        """
        self.artifactdirectory_ = artifactdirectory
        if not os.path.exists(artifactdirectory):
            raise HTTPJsonError(
                ERROR_CODES.NO_ARTIFACT_DIR,
                "Artifact directory {path} does not exist or is inaccessible)",
                {"path": artifactdirectory},
            )

        self._elf_symbol = CSLDebug.CSLELFSymbol(self.artifactdirectory_)

        self.populate_elf_map()

        self.colors = []
        # Directory contains proper ELF files
        if self._elf_symbol.dimensions().area():
            self._elf_symbol.init_symbol(True)
            self.colors = self._elf_symbol.symbol_table.get_routing_colors()

        # key = int(color), value = Set(known names)
        self._known_names_dict = None

    def getFabricSize(self) -> tuple():
        d = self._elf_symbol.dimensions()
        return (d.width(), d.height())

    def get_pre_run_routes_raw(self, x, y):
        return self._elf_symbol.symbol_table.get_pre_run_routes_raw(x, y)

    def populate_elf_map(self):
        elf_files = [
            os.path.join(self.artifactdirectory_, f)
            for f in os.listdir(self.artifactdirectory_)
            if os.path.isfile(os.path.join(self.artifactdirectory_, f))
            and f.endswith('.elf')
        ]

        self.elf_file_map_ = {}
        for elf_file in elf_files:
            elf_memory = ELFMemory(elf_file)
            coords = elf_memory.iter_coordinates()
            for coord in coords:
                key = str(coord)
                self.elf_file_map_[key] = elf_file

    def get_colors(self):
        return self.colors

    def _populate_color_name(self, color_info_list: list):
        """
        Populate color index and names to known_names_dict
        Example:
        color:0, known_names ["RXACT_CMD"]
        [
          {'id': 0, 'rx': ['west'], 'tx': ['ramp', 'east'], 'known_names': ['RXACT_CMD']},
          ...
        ]
        """
        for info in color_info_list:
            if "id" not in info or "known_names" not in info:
                continue

            color_idx = info["id"]
            color_names = info["known_names"]
            if color_idx not in self._known_names_dict:
                self._known_names_dict[color_idx] = set()
            self._known_names_dict[color_idx] |= set(color_names)

    def _parse_elf_color_info(self, elf_path):
        """
        Use the elf/csl library to get the color info in pe_debug_info in ELF.
        """
        with open(elf_path, "rb") as f:
            if has_color_info(f):
                pe_debug_info = get_color_info(f)
                for debug_info in pe_debug_info:
                    if self.COLOR_INFO in debug_info:
                        self._populate_color_name(debug_info[self.COLOR_INFO])

    def get_color_names(self) -> defaultdict:
        """
        Parse all the ELF generated by CSL compiler and populate known names.
        Returns a dict(int, set(str)). The key represents the color index
        the value is set of variables names from user.
        """
        # Initialize known name for the first time
        if self._known_names_dict is None:
            self._known_names_dict = defaultdict(lambda: None)
            for elf_path in self._elf_symbol.elf_files:
                self._parse_elf_color_info(elf_path)

        return self._known_names_dict

    def get_task_map(self, x, y):
        tasks = {}
        key = str((x, y))
        if key not in self.elf_file_map_:
            return tasks
        
        elf_file = self.elf_file_map_[key]
        for task_id in range(64):
            if task_id == 31:
                continue
            elf = ELFMemory(elf_file)
            names = list(elf.get_task_names(x, y, task_id))
            if len(names) > 0:
                tasks[task_id] = ",".join(names)
        
        return tasks
