"""
api/gsv/ufv/pe_compile_info
return the ucode and casm compile params of a pe
"""

from pathlib import Path

import yaml

from cerebras.hwdebug_common.viz_service.base import PluginBase
from cerebras.hwdebug_common.viz_service.plugins.common.utils import (
    query_string_to_request,
)
from cerebras.hwdebug_common.viz_service.plugins.gsv.ufv.ufv_common import (
    validate_chief_dir,
)
from cerebras.pb.viz.unified_fabric_viewer_pb2 import GetPeCompileInfoRequest
from cerebras.stack.tools.contextpy import CsContext
from cerebras.ws.hwdebug.lib.unifiedfabricvizpybind import UnifiedFabricViz


class Plugin(PluginBase):
    ALIAS = 'gsv/ufv/annotation'

    def handle_get(self, handler, url, req, qs):
        """parse the v1 request and dispatch as appropriate"""
        self.logger.debug("%s GET: %s", Plugin.ALIAS, url)
        self.handler = handler

        req = GetPeCompileInfoRequest()
        query_string_to_request(qs, req)
        error = validate_chief_dir(req.chief_directory)
        if error:
            self.return_validation_error(error)
            return True

        # additional check: this plugin depends on ufv_ctx_id.json or .pbbin
        ufv_ctx_id_json = (
            Path(req.chief_directory) / "stall_viz/ufv_ctx_id.json"
        )
        ufv_ctx_id_pbbin = (
            Path(req.chief_directory) / "stall_viz/ufv_ctx_id.pbbin"
        )
        if (not ufv_ctx_id_json.exists()) and (not ufv_ctx_id_pbbin.exists()):
            self.return_validation_error(
                f"Cannot find ctx_id heatmap generated by stall_viz"
            )
            return True

        # load in the ws_img_ini.yaml file
        ws_img_ini = Path(req.chief_directory) / "ws_img_ini.yaml"
        existing_inis = CsContext().config_dump_dict()
        if not ws_img_ini.exists():
            self.return_validation_error(
                f"Cannot find ws_img_ini.yaml in chief directory"
            )
            return True
        else:
            self.logger.info("Loading inis from ws_img_ini.yaml")
            config = yaml.safe_load(ws_img_ini.read_text())
            config = config if config != None else dict()

            # Don't replace any existing inis
            config = {k: v for k, v in config.items() if k not in existing_inis}
            config.update(existing_inis)

            # cs_context requires clearing before calling config_set a second time
            CsContext().config_clear()
            CsContext().config_set(config)

        ufv = UnifiedFabricViz(req.chief_directory)
        resp = ufv.get_pe_compile_info(req.pe_x, req.pe_y)
        dict = self.msg_to_dict(resp)
        self.return_json(dict, compress=True)

        # clearing context before returning from function
        CsContext().config_clear()
        CsContext().config_set(existing_inis)
        return True
